def main() -> None:
    with TRANSLATED.open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        fields = reader.fieldnames
        rows = list(reader)
    if not fields:
        raise SystemExit("missing CSV header")
    by_key = {(row["source file"], row["offset"]): row for row in rows}
    planned = dict(NEW)
    for target, reference in COPIES.items():
        dst = by_key.get(target)
        src = by_key.get(reference)
        if not dst or not src or not src["korean"]:
            raise SystemExit(f"missing completed copy source: {target} <- {reference}")
        if dst["japanese"] != src["japanese"]:
            raise SystemExit(f"Japanese mismatch in copy pair: {target} <- {reference}")
        planned[target] = src["korean"]

    # Repeated dialogue is common in the area files.  Copy only an exact,
    # complete Japanese match for which every completed occurrence agrees on
    # one Korean string; controls, unresolved source, and ambiguous matches are
    # excluded.  This never invents or rewrites a translation.
    known = {}
    for row in rows:
        japanese = row["japanese"]
        if row["korean"] and "<G:" not in japanese and "<CTRL:" not in japanese:
            known.setdefault(japanese, set()).add(row["korean"])
    for row in rows:
        japanese = row["japanese"]
        key = row["source file"], row["offset"]
        if (
            not row["korean"]
            and "<G:" not in japanese
            and "<CTRL:" not in japanese
            and len(known.get(japanese, ())) == 1
        ):
            planned.setdefault(key, next(iter(known[japanese])))

    # A partial Japanese decode is never a translation target.  This comes first
    # so a past or future batch cannot leave an apparently complete Korean line
    # attached to a row that still has an unresolved original-font glyph.
    cleared = 0
    for row in rows:
        if "<G:" in row["japanese"] and (row["korean"] or row["source of the translation (existing / new)"]):
            row["korean"] = ""
            row["source of the translation (existing / new)"] = ""
            cleared += 1

    applied = 0
    already_applied = 0
    for row in rows:
        key = row["source file"], row["offset"]
        if key not in planned:
            continue
        if "<G:" in row["japanese"]:
            raise SystemExit(f"planned translation has unresolved glyph: {key}")
        source = row["source of the translation (existing / new)"]
        if source == "existing":
            raise SystemExit(f"refusing to overwrite existing translation: {key}")
        if source not in ("", "new"):
            raise SystemExit(f"unexpected source state for {key}")
        if source == "new":
            if row["korean"] != planned[key]:
                raise SystemExit(f"refusing to change completed new translation: {key}")
            already_applied += 1
            continue
        row["korean"] = planned[key]
        row["source of the translation (existing / new)"] = "new"
        applied += 1
    found = applied + already_applied
    if found != len(planned):
        raise SystemExit(f"only found {found}/{len(planned)} planned rows")
    with TRANSLATED.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader(); writer.writerows(rows)

    mapped = set()
    for name in ("korean_charmap.csv", "korean_charmap_extended.csv"):
        with (DOCS / name).open(encoding="utf-8-sig", newline="") as f:
            mapped |= {row["char"] for row in csv.DictReader(f)}
    freq = Counter(ch for row in rows for ch in row["korean"] if "가" <= ch <= "힣")
    with SYLLABLES.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["syllable", "frequency", "has existing glyph"])
        writer.writeheader()
        for ch, n in freq.most_common():
            writer.writerow({"syllable": ch, "frequency": n, "has existing glyph": int(ch in mapped)})
    readable_blank = sum(
        bool(
            not row["korean"]
            and "<G:" not in row["japanese"]
            and row["japanese"].strip()
            and "<CTRL:" not in row["japanese"]
        )
        for row in rows
    )
    control_blank = sum(
        bool(not row["korean"] and "<G:" not in row["japanese"] and "<CTRL:" in row["japanese"])
        for row in rows
    )
    unresolved_blank = sum(
        bool(not row["korean"] and "<G:" in row["japanese"])
        for row in rows
    )
